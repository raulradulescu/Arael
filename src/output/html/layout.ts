function baseScript(): string {
  return `
    (function () {
      function textFor(row) {
        return row.textContent.toLowerCase();
      }
      function applyFilters(tableId) {
        var table = document.getElementById(tableId);
        if (!table) return;
        var searchInputs = document.querySelectorAll('[data-search-target="' + tableId + '"]');
        var solvedToggles = document.querySelectorAll('[data-solved-toggle="' + tableId + '"]');
        var query = '';
        searchInputs.forEach(function (input) {
          query += ' ' + String(input.value || '').toLowerCase();
        });
        query = query.trim();
        var solvedOnly = false;
        solvedToggles.forEach(function (toggle) {
          solvedOnly = solvedOnly || toggle.checked;
        });
        table.querySelectorAll('tbody tr').forEach(function (row) {
          var matchesQuery = !query || textFor(row).indexOf(query) !== -1;
          var matchesSolved = !solvedOnly || row.getAttribute('data-solved') === 'true';
          row.style.display = matchesQuery && matchesSolved ? '' : 'none';
        });
      }
      document.querySelectorAll('[data-search-target]').forEach(function (input) {
        input.addEventListener('input', function () {
          applyFilters(input.getAttribute('data-search-target'));
        });
      });
      document.querySelectorAll('[data-solved-toggle]').forEach(function (input) {
        input.addEventListener('change', function () {
          applyFilters(input.getAttribute('data-solved-toggle'));
        });
      });
      document.querySelectorAll('th[data-sortable="true"]').forEach(function (th) {
        th.addEventListener('click', function () {
          var table = th.closest('table');
          if (!table || !table.tBodies.length) return;
          var index = Array.prototype.indexOf.call(th.parentNode.children, th);
          var direction = th.getAttribute('data-sort-dir') === 'asc' ? 'desc' : 'asc';
          th.parentNode.querySelectorAll('th').forEach(function (other) {
            other.removeAttribute('data-sort-dir');
          });
          th.setAttribute('data-sort-dir', direction);
          var rows = Array.from(table.tBodies[0].rows);
          rows.sort(function (left, right) {
            var leftText = (left.cells[index] && left.cells[index].getAttribute('data-sort-value')) || (left.cells[index] && left.cells[index].textContent) || '';
            var rightText = (right.cells[index] && right.cells[index].getAttribute('data-sort-value')) || (right.cells[index] && right.cells[index].textContent) || '';
            var leftNum = Number(String(leftText).replace(/[^0-9.+-]/g, ''));
            var rightNum = Number(String(rightText).replace(/[^0-9.+-]/g, ''));
            var result = Number.isFinite(leftNum) && Number.isFinite(rightNum)
              ? leftNum - rightNum
              : String(leftText).localeCompare(String(rightText), undefined, { numeric: true, sensitivity: 'base' });
            return direction === 'asc' ? result : -result;
          });
          rows.forEach(function (row) {
            table.tBodies[0].appendChild(row);
          });
        });
      });
      document.querySelectorAll('[data-copy]').forEach(function (button) {
        button.addEventListener('click', function () {
          var text = button.getAttribute('data-copy') || '';
          var done = function () {
            var previous = button.textContent;
            button.textContent = 'Copied';
            setTimeout(function () { button.textContent = previous; }, 1000);
          };
          if (navigator.clipboard && navigator.clipboard.writeText) {
            navigator.clipboard.writeText(text).then(done).catch(function () {});
          } else {
            var area = document.createElement('textarea');
            area.value = text;
            document.body.appendChild(area);
            area.select();
            try { document.execCommand('copy'); done(); } catch (error) {}
            document.body.removeChild(area);
          }
        });
      });
    }());
  `;
}
