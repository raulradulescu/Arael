import { escapeHtml } from './escape';

export interface HtmlDocumentOptions {
  title: string;
  body: string;
  generatedAt?: Date | string;
  extraStyles?: string;
}

export function renderHtmlDocument(options: HtmlDocumentOptions): string {
  const generatedAt = dateFromInput(options.generatedAt);
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(options.title)}</title>
  <style>
${baseStyles()}
${options.extraStyles ?? ''}
  </style>
</head>
<body>
${options.body}
  <footer>
    <p>Generated by <a href="https://github.com/raulradulescu/arael">Arael</a> - Reverse Engineering Assistant</p>
    <p class="footer-meta">Timestamp: ${escapeHtml(generatedAt.toISOString())}</p>
  </footer>
  <script>
${baseScript()}
  </script>
</body>
</html>`;
}

export function formatGeneratedDate(value?: Date | string): string {
  return dateFromInput(value).toLocaleString('en-US', {
    dateStyle: 'medium',
    timeStyle: 'short'
  });
}

function dateFromInput(value?: Date | string): Date {
  if (value instanceof Date) {
    return value;
  }
  if (typeof value === 'string') {
    const parsed = new Date(value);
    if (!Number.isNaN(parsed.getTime())) {
      return parsed;
    }
  }
  return new Date();
}

